// 生成 luowen/web/colors/materialized.js：把 token 规范的已复算产物（62 类型→hex）
// 与 component 层（width/flow）、context（对比度参照底色）打包为运行时可 import 的 ES 模块。
// 单一来源仍是 token JSON 与 data/*.json；本脚本只做搬运与格式化，不做任何颜色计算。
// 用法：node docs/specs/link-color-tokens/materialize.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const OUT = join(here, '..', '..', '..', 'luowen', 'web', 'colors', 'materialized.js');

const themes = {};
for (const id of ['luowen-dark', 'luowen-cyberpunk', 'luowen-nightlight']) {
  const short = id.replace(/^luowen-/, '');
  const token = JSON.parse(readFileSync(join(here, `luowen-${short}.tokens.json`), 'utf8'));
  const data = JSON.parse(readFileSync(join(here, 'data', `link-colors-${id}.json`), 'utf8'));
  themes[id] = {
    id: token.id ?? id,
    name: token.name ?? id,
    context: token.context,
    width: data.width ?? token.component?.connection?.width ?? 3,
    flow: token.component?.connection?.flow ?? { enabled: false, dash: 7, gap: 13, speed: 48, opacity: 0.92 },
    tokens: data.tokens,
    types: data.types,
    typeRules: token.typeRules ?? [],
  };
}

const banner = `// GENERATED by docs/specs/link-color-tokens/materialize.mjs — 请勿手改。
// 再生成：node docs/specs/link-color-tokens/materialize.mjs
// 来源：luowen-{dark,cyberpunk,nightlight}.tokens.json + data/link-colors-*.json（verify.mjs --emit-hex 产物）。
// 门槛（对比度 / 色盲 ΔE / 62 类覆盖）已在 token 层验证，见 docs/specs/link-color-tokens/。
export const THEMES = ${JSON.stringify(themes, null, 2)};
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, banner, 'utf8');
console.log('written', OUT, 'themes:', Object.keys(themes).join(', '), 'types:', Object.keys(themes['luowen-dark'].types).length);
